function loadRecent() {
  try {
    const raw = JSON.parse(localStorage.getItem(LS) || "[]");
    return Array.isArray(raw) ? raw.filter((x) => typeof x === "string").slice(0, 32) : [];
  } catch {
    return [];
  }
}

export function rememberEmoji(ch) {
  const next = [ch, ...loadRecent().filter((x) => x !== ch)].slice(0, 32);
  localStorage.setItem(LS, JSON.stringify(next));
}

export function allEmoji() {
  const set = new Set();
  for (const c of CATS) {
    if (c.id === "recent") continue;
    for (const e of c.items) set.add(e);
  }
  return [...set];
}

export function mountEmojiPicker(host, { onPick, locale = "ru" } = {}) {
  host.innerHTML = "";
  host.className = "emo";
  let cat = loadRecent().length ? "recent" : "smileys";
  let q = "";

  const search = document.createElement("div");
  search.className = "emo-search";
  search.innerHTML = `<span>🔍</span><input type="search" placeholder="${locale === "ru" ? "Поиск эмодзи" : "Search emoji"}" />`;
  const input = search.querySelector("input");

  const tabs = document.createElement("div");
  tabs.className = "emo-tabs";

  const grid = document.createElement("div");
  grid.className = "emo-grid nl-scroll";

  function itemsFor() {
    if (q.trim()) {
      const needle = q.trim().toLowerCase();
      return allEmoji().filter((e) => e.includes(needle) || true).filter(() => true);
    }
    if (cat === "recent") return loadRecent();
    return CATS.find((c) => c.id === cat)?.items ?? [];
  }

  function paintGrid() {
    const items = q.trim()
      ? allEmoji()
      : cat === "recent"
        ? loadRecent()
        : (CATS.find((c) => c.id === cat)?.items ?? []);
    grid.innerHTML = "";
    if (!items.length) {
      const empty = document.createElement("div");
      empty.className = "emo-empty";
      empty.textContent = locale === "ru" ? "Пока пусто — выберите эмодзи" : "Nothing here yet";
      grid.appendChild(empty);
      return;
    }
    const frag = document.createDocumentFragment();
    for (const e of items) {
      const b = document.createElement("button");
      b.type = "button";
      b.textContent = e;
      b.title = e;
      b.addEventListener("click", () => {
        rememberEmoji(e);
        onPick?.(e);
      });
      frag.appendChild(b);
    }
    grid.appendChild(frag);
  }

  function paintTabs() {
    tabs.innerHTML = "";
    for (const c of CATS) {
      const b = document.createElement("button");
      b.type = "button";
      b.textContent = c.icon;
      b.title = locale === "ru" ? c.ru : c.en;
      b.className = c.id === cat && !q ? "on" : "";
      b.addEventListener("click", () => {
        cat = c.id;
        q = "";
        input.value = "";
        paintTabs();
        paintGrid();
      });
      tabs.appendChild(b);
    }
  }

  input.addEventListener("input", () => {
    q = input.value;
    paintTabs();
    paintGrid();
  });

  host.append(search, tabs, grid);
  paintTabs();
  paintGrid();
  return {
    focus: () => input.focus(),
    refresh: () => paintGrid(),
  };
}
